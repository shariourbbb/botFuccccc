import * as dbm from './db.js';
import fs from 'node:fs';
const d = dbm.db;
const out = {};
out.admins = d.get_admins();
out.stats = d.get_stats();
out.categories = d.get_categories();
out.cat_row = d.get_category_row_size();
out.sub_row = d.get_subcategory_row_size();
out.min_wdr = d.get_min_withdraw_amount();
out.users_page = d.get_paginated_users(1, 2);
out.courses = Object.keys(d.get_all_courses());
out.ebooks = Object.keys(d.get_all_ebooks());
out.subcats_ssc = d.get_subcategories('📚 SSC');
out.courses_by_cat = d.get_courses_by_filter({ category: ' SSC' }).map((c) => c.id);
out.coupons = Object.keys(d.get_all_coupons());
out.pending_orders = d.get_pending_orders().length;
out.pending_wdr = d.get_pending_withdrawals().length;
out.payment_note = d.get_payment_note().slice(0, 40);
out.referral_enabled = d.is_referral_enabled();
out.reward = d.get_referral_reward_amount();
out.home_btn = d.is_home_button_enabled();
out.view_all = d.is_view_all_courses_enabled();
out.categories_tree = d.get_sub_folders('', true);
out.settings_keys = Object.keys(d.settings).sort();
out.kb = Object.keys(d.get_custom_keyboards());
out.perm_defs = Object.keys(dbm.ADMIN_PERMISSION_DEFINITIONS);
fs.writeFileSync('node_dump.json', JSON.stringify(out, null, 1), 'utf-8');
console.log('NODE DUMP OK');
